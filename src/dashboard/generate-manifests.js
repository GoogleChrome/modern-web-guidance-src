import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';

import { outDir, suitesDir, guidesDir, dashboardDir } from '../core/paths.ts';

const defaultOutputDir = path.join(outDir, 'dashboard');

/** 
 * Scans guides for web-feature-ids in frontmatter and generates window.__featuresMapping.
 */
export function generateMapping(outputDir = defaultOutputDir) {
    if (!fs.existsSync(guidesDir)) {
        throw new Error(`guidesDir not found at ${guidesDir}`);
    }
    fs.mkdirSync(outputDir, { recursive: true });
    /** @type {Record<string, string[]>} */
    const mapping = {}; // usecase -> [feature_ids]

    /** @param {string} dir */
    function scanGuides(dir) {
        if (!fs.existsSync(dir)) return;
        const items = fs.readdirSync(dir, { withFileTypes: true });
        for (const item of items) {
            if (item.isDirectory()) {
                const subDir = path.join(dir, item.name);
                const guidePath = path.join(subDir, 'guide.md');
                if (fs.existsSync(guidePath)) {
                    const text = fs.readFileSync(guidePath, 'utf8');
                    const parsed = matter(text);
                    if (parsed.data && parsed.data['web-feature-ids']) {
                        const features = parsed.data['web-feature-ids'];
                        if (Array.isArray(features) && features.length > 0) {
                            mapping[item.name] = features;
                        }
                    }
                }
                scanGuides(subDir); // recurse
            }
        }
    }

    scanGuides(guidesDir);

    const outputFilePath = path.join(outputDir, 'features-mapping.gen.js');
    const jsContent = `// Automatically generated by generate-manifests.js. Do not edit.\nwindow.__featuresMapping = ${JSON.stringify(mapping, null, 2)};\n`;
    fs.writeFileSync(outputFilePath, jsContent);
    return mapping;
}

/** 
 * Generates suites.gen.json based on folders in results/suites that contain evals.json.
 */
export async function generateSuitesManifest(outputDir = defaultOutputDir, resultsSourceDir = suitesDir) {
    fs.mkdirSync(outputDir, { recursive: true });
    const { extractSuiteSummary } = await import('./summary-extractor.js');
    /** @type {Map<string, Record<string, any>>} */
    const suitesMap = new Map();
    const outputPath = path.join(outputDir, 'suites.gen.json');

    // Add suites from results dir
    if (fs.existsSync(resultsSourceDir)) {
        const items = fs.readdirSync(resultsSourceDir, { withFileTypes: true });
        for (const item of items) {
            if (item.isDirectory()) {
                const suiteDir = path.join(resultsSourceDir, item.name);
                const evalsPath = path.join(suiteDir, 'evals.json');
                if (fs.existsSync(evalsPath)) {
                    try {
                        const rawData = JSON.parse(fs.readFileSync(evalsPath, 'utf8'));
                        const summary = extractSuiteSummary(item.name, rawData);
                        if (summary) {
                            suitesMap.set(item.name, summary);
                        }
                    } catch (e) {
                        console.warn(`Failed to parse evals.json for ${item.name}:`, e);
                        suitesMap.set(item.name, { testId: item.name, source: 'local' });
                    }
                }
            }
        }
    }

    const sortedSuites = Array.from(suitesMap.values()).sort((a, b) => {
        return (a.testId || '').localeCompare(b.testId || '');
    });
    fs.writeFileSync(outputPath, JSON.stringify(sortedSuites, null, 2));
    return sortedSuites;
}

export async function generateGroupedTasksManifest(outputDir = defaultOutputDir) {
    fs.mkdirSync(outputDir, { recursive: true });
    const { getTaskMap } = await import('../core/guide-validation.ts');
    const taskMap = getTaskMap();
    /** @type {Record<string, Record<string, string[]>>} */
    const grouped = {};
    
    for (const [key, info] of taskMap.entries()) {
        const [guide, task] = key.split('/');
        const category = (info && info.guideDir)
            ? path.basename(path.dirname(info.guideDir))
            : 'Uncategorized';
        if (!grouped[category]) grouped[category] = {};
        if (!grouped[category][guide]) grouped[category][guide] = [];
        grouped[category][guide].push(task);
    }
    
    const outputPath = path.join(outputDir, 'grouped-tasks.gen.json');
    fs.writeFileSync(outputPath, JSON.stringify({ guides: grouped }, null, 2));
}

/** @type {Record<string, string>} */
const CATEGORY_TITLES = {
    'css': 'CSS',
    'html': 'HTML',
    'js': 'JavaScript',
    'pwa': 'PWA',
    'webmcp': 'WebMCP',
    'built-in-ai': 'Built-in AI',
    'ui-atoms': 'UI Atoms',
    'ui-behaviors': 'UI Behaviors',
    'ui-components': 'UI Components',
    'visual-design': 'Visual Design'
};

/**
 * @param {string} cat
 * @returns {string}
 */
export function formatCategoryTitle(cat) {
    if (CATEGORY_TITLES[cat]) return CATEGORY_TITLES[cat];
    return cat.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

/**
 * Scans guides for demo HTML files and produces demos.gen.json & demos.gen.js.
 */
export function generateDemosManifest(outputDir = defaultOutputDir) {
    if (!fs.existsSync(guidesDir)) {
        throw new Error(`guidesDir not found at ${guidesDir}`);
    }
    fs.mkdirSync(outputDir, { recursive: true });

    /**
     * @typedef {{
     *   id: string;
     *   label: string;
     *   file: string;
     *   path: string;
     * }} DemoFile
     * 
     * @typedef {{
     *   id: string;
     *   slug: string;
     *   category: string;
     *   categoryTitle: string;
     *   title: string;
     *   description: string;
     *   features: string[];
     *   dir: string;
     *   demos: DemoFile[];
     * }} DemoGuide
     */

    /** @type {DemoGuide[]} */
    const guides = [];

    /** @param {string} dir */
    function scanGuides(dir) {
        if (!fs.existsSync(dir)) return;
        const items = fs.readdirSync(dir, { withFileTypes: true });
        for (const item of items) {
            if (item.isDirectory()) {
                const subDir = path.join(dir, item.name);
                const demoPath = path.join(subDir, 'demo.html');
                if (fs.existsSync(demoPath)) {
                    const guidePath = path.join(subDir, 'guide.md');
                    let title = item.name;
                    let description = '';
                    /** @type {string[]} */
                    let features = [];

                    if (fs.existsSync(guidePath)) {
                        try {
                            const parsed = matter(fs.readFileSync(guidePath, 'utf8'));
                            const titleMatch = parsed.content.match(/^#\s+(.+)$/m);
                            if (titleMatch) title = titleMatch[1].trim();
                            if (parsed.data) {
                                description = parsed.data.description || '';
                                if (Array.isArray(parsed.data['web-feature-ids'])) {
                                    features = parsed.data['web-feature-ids'];
                                }
                            }
                        } catch (err) {
                            console.warn(`Failed to parse guide.md at ${guidePath}:`, err);
                        }
                    }

                    const relDir = path.relative(guidesDir, subDir);
                    const parts = relDir.split(path.sep);
                    const category = parts[0];
                    const guideSlug = parts.slice(1).join('/');
                    const categoryTitle = formatCategoryTitle(category);

                    const demoFiles = [];
                    const filesInDir = fs.readdirSync(subDir);
                    if (filesInDir.includes('demo.html')) {
                        demoFiles.push({
                            id: 'demo',
                            label: 'Recommended',
                            file: 'demo.html',
                            path: `guides/${relDir}/demo.html`
                        });
                    }
                    if (filesInDir.includes('negative-demo.html')) {
                        demoFiles.push({
                            id: 'negative-demo',
                            label: 'Anti-Pattern',
                            file: 'negative-demo.html',
                            path: `guides/${relDir}/negative-demo.html`
                        });
                    }
                    for (const f of filesInDir) {
                        if (f.startsWith('demo-') && f.endsWith('.html')) {
                            const variant = f.slice(5, -5).replace(/[-_]/g, ' ');
                            demoFiles.push({
                                id: f.slice(0, -5),
                                label: variant.charAt(0).toUpperCase() + variant.slice(1),
                                file: f,
                                path: `guides/${relDir}/${f}`
                            });
                        }
                    }

                    guides.push({
                        id: item.name,
                        slug: guideSlug,
                        category,
                        categoryTitle,
                        title,
                        description,
                        features,
                        dir: `guides/${relDir}`,
                        demos: demoFiles
                    });
                }
                scanGuides(subDir);
            }
        }
    }

    scanGuides(guidesDir);

    // Sort guides alphabetically by category, then by title
    guides.sort((a, b) => {
        if (a.category !== b.category) return a.category.localeCompare(b.category);
        return a.title.localeCompare(b.title);
    });

    const categories = Array.from(new Set(guides.map(g => g.category)));
    const manifest = {
        count: guides.length,
        categories,
        guides
    };

    const jsonPath = path.join(outputDir, 'demos.gen.json');
    fs.writeFileSync(jsonPath, JSON.stringify(manifest, null, 2));

    const jsPath = path.join(outputDir, 'demos.gen.js');
    fs.writeFileSync(jsPath, `// Automatically generated by generate-manifests.js. Do not edit.\nwindow.__demosManifest = ${JSON.stringify(manifest, null, 2)};\n`);

    return manifest;
}

const DEMO_STATIC_EXTS = new Set(['.html', '.css', '.js', '.svg', '.png', '.jpg', '.jpeg', '.webp', '.json']);

/**
 * Recursively copies demo files and static assets from guides into the destination directory,
 * skipping test targets and hidden files.
 * @param {string} src
 * @param {string} dest
 */
function copyDemoAssets(src, dest) {
    if (!fs.existsSync(src)) return;
    for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
        if (entry.name === 'targets' || entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
        const srcPath = path.join(src, entry.name);
        const destPath = path.join(dest, entry.name);
        if (entry.isDirectory()) {
            copyDemoAssets(srcPath, destPath);
        } else if (DEMO_STATIC_EXTS.has(path.extname(entry.name).toLowerCase())) {
            fs.mkdirSync(dest, { recursive: true });
            fs.copyFileSync(srcPath, destPath);
        }
    }
}

/**
 * Copies dashboard static files, generated manifests, and guide demos into out/dashboard-pages/ for deployment.
 */
export function stagePages(stageDir = path.join(outDir, 'dashboard-pages'), manifestsDir = defaultOutputDir) {
    fs.rmSync(stageDir, { recursive: true, force: true });
    fs.mkdirSync(stageDir, { recursive: true });

    // Copy static files from dashboardDir (.html, .js, .css, .svg, .png, etc.)
    const staticExts = new Set(['.html', '.js', '.css', '.svg', '.png', '.jpg', '.jpeg', '.gif', '.ico']);
    for (const file of fs.readdirSync(dashboardDir)) {
        if (file.endsWith('.test.ts') || file.endsWith('.spec.js') || file.startsWith('.')) continue;
        const ext = path.extname(file);
        if (staticExts.has(ext)) {
            fs.copyFileSync(path.join(dashboardDir, file), path.join(stageDir, file));
        }
    }

    // Copy generated manifests from out/dashboard
    if (fs.existsSync(manifestsDir)) {
        for (const file of fs.readdirSync(manifestsDir)) {
            if (file.includes('.gen.')) {
                fs.copyFileSync(path.join(manifestsDir, file), path.join(stageDir, file));
            }
        }
    }

    // Copy guide demo files and static assets into guides/
    if (fs.existsSync(guidesDir)) {
        copyDemoAssets(guidesDir, path.join(stageDir, 'guides'));
    }
}

/**
 * Main CLI Orchestrator
 */
export async function runAllManifests({ resultsOnly = false, outputDir = defaultOutputDir } = {}) {
    fs.mkdirSync(outputDir, { recursive: true });
    if (!resultsOnly) {
        console.log('🔄 Generating features mapping...');
        generateMapping(outputDir);
        console.log('🔄 Generating grouped tasks manifest...');
        await generateGroupedTasksManifest(outputDir);
        console.log('🔄 Generating demos manifest...');
        generateDemosManifest(outputDir);
    }

    console.log('🔄 Generating suites manifests...');
    await generateSuitesManifest(outputDir);
}

// CLI Runner
const isMain = process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
if (isMain) {
    const args = process.argv.slice(2);
    const resultsOnly = args.includes('--results-only');
    const doStagePages = args.includes('--stage-pages');
    try {
        await runAllManifests({ resultsOnly });
        if (doStagePages) {
            console.log('🔄 Staging dashboard pages for deployment...');
            stagePages();
        }
        console.log('✅ All manifests generated successfully.');
    } catch (e) {
        console.error('❌ Error generating manifests:', e);
        process.exit(1);
    }
}
